"""rank writes the gistable report.md and results.json artifacts."""

from __future__ import annotations

import json
import socket
import sys
from pathlib import Path

import pytest
from typer.testing import CliRunner

import quantproof
from quantproof.cli import app

CLI = CliRunner()
STUB = Path(__file__).parent / "stub_llama_server.py"


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def rank_argv(tmp_path: Path, extra: list[str]) -> list[str]:
    """A two-variant rank run against the stub: Q4_K_M at 100%, IQ2_XXS collapsed."""
    pack_dir = tmp_path / "tasks"
    pack_dir.mkdir()
    (pack_dir / "tasks.json").write_text(
        json.dumps(
            {
                "base_model": "Some/Model",
                "k_samples": 1,
                "tasks": [
                    {
                        "id": "france",
                        "prompt": "What is the capital of France? Reply with just the city name.",
                        "grader": {"type": "contains", "expected": "Paris"},
                    },
                    {"id": "ping", "prompt": "Say PONG", "grader": {"type": "contains", "expected": "PONG"}},
                ],
            }
        ),
        encoding="utf-8",
    )
    good = tmp_path / "Model.Q4_K_M.gguf"
    collapsed = tmp_path / "Model.IQ2_XXS.gguf"
    good.write_bytes(b"stub-model-file")
    collapsed.write_bytes(b"stub-model-file")
    server = " ".join([sys.executable, str(STUB), "--default-response", "PONG"])
    return [
        "rank",
        "--gguf",
        str(good),
        "--gguf",
        str(collapsed),
        "--tasks",
        str(pack_dir),
        "--port",
        str(free_port()),
        "--server-bin",
        server,
        *extra,
    ]


def test_rank_writes_artifacts_to_out_dir(tmp_path: Path) -> None:
    out = tmp_path / "artifacts" / "run1"
    result = CLI.invoke(app, rank_argv(tmp_path, ["--out", str(out)]), env={"COLUMNS": "120"})
    assert result.exit_code == 0, result.output
    assert "report written to" in result.output

    report = (out / "report.md").read_text(encoding="utf-8")
    assert report.startswith("# QuantProof report — Some/Model")
    assert "| Q4_K_M | 100.0% | baseline" in report
    assert "IQ2_XXS" in report and "-50.0 pp" in report
    assert "**collapse:** IQ2_XXS (-50.0 pp) versus Q4_K_M on your tasks" in report
    assert "## Per-task pass rate" in report
    assert "| france | contains | 1/1 | 0/1 |" in report
    assert report.rstrip().endswith(f"Generated by quantproof {quantproof.__version__}.")

    payload = json.loads((out / "results.json").read_text(encoding="utf-8"))
    assert payload["base_model"] == "Some/Model"
    assert payload["k_samples"] == 1
    assert payload["task_count"] == 2
    assert payload["reference"]["variant"] == "Q4_K_M"
    assert [row["variant"] for row in payload["rows"]] == ["Q4_K_M", "IQ2_XXS"]
    reference_score = payload["reference"]["score"]
    for row in payload["rows"]:
        assert payload["deltas"][row["variant"]] == pytest.approx(row["score"] - reference_score)
    assert payload["generated_by"].startswith("quantproof 0.")


def test_rank_artifacts_default_to_cwd(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.chdir(tmp_path)
    result = CLI.invoke(app, rank_argv(tmp_path, []), env={"COLUMNS": "120"})
    assert result.exit_code == 0, result.output
    assert (tmp_path / "report.md").is_file()
    assert (tmp_path / "results.json").is_file()


def test_rank_terminal_table_output_unchanged(tmp_path: Path) -> None:
    """The console report keeps its shape; the artifacts are additive."""
    result = CLI.invoke(
        app, rank_argv(tmp_path, ["--out", str(tmp_path / "o")]), env={"COLUMNS": "120"}
    )
    assert result.exit_code == 0, result.output
    assert "Quant calibration — ranked on your tasks" in result.output
    assert "collapse:" in result.output
    assert "Per-task pass rate" in result.output
